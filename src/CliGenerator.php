<?php

declare(strict_types=1);

namespace EidCloud\ApiCli;

use EidCloud\ApiCli\Parser\SpecParser;
use RuntimeException;

/**
 * Generates standalone CLI executables from OpenAPI specifications.
 */
class CliGenerator
{
    private SpecParser $parser;

    public function __construct(SpecParser $parser)
    {
        $this->parser = $parser;
    }

    /**
     * Builds and compiles a standalone CLI script for the parsed API.
     */
    public function generate(string $name, string $outputDir): string
    {
        if (!is_dir($outputDir)) {
            @mkdir($outputDir, 0755, true);
        }

        $operations = $this->parser->getOperations();
        $title = $this->parser->getTitle();
        $version = $this->parser->getVersion();
        $description = addslashes($this->parser->getDescription());
        $baseUrl = $this->parser->getBaseUrl();

        $tree = [];
        foreach ($operations as $op) {
            $resource = $op['resource'];
            $action = $this->extractAction($op['method'], $op['path'], $op['operationId']);
            $tree[$resource][$action] = $op;
        }

        $serializedTree = var_export($tree, true);

        $template = <<<PHP
#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Auto-generated CLI for {$title} v{$version}
 * Generated by EidCloud API CLI Generator (eidcloud-api-cli)
 * Zero external vendor dependencies - Pure PHP 8.2+
 */

require_once __DIR__ . '/../src/Autoloader.php';
\\EidCloud\\ApiCli\\Autoloader::register();

use EidCloud\\ApiCli\\Client\\HttpClient;
use EidCloud\\ApiCli\\Auth\\AuthManager;
use EidCloud\\ApiCli\\Formatter\\TableFormatter;
use EidCloud\\ApiCli\\Validator\\RequestValidator;
use EidCloud\\ApiCli\\Command\\PaginationHandler;

\$title = "{$title}";
\$version = "{$version}";
\$baseUrl = "{$baseUrl}";
\$commands = {$serializedTree};

\$formatter = new TableFormatter();
\$authManager = new AuthManager();
\$validator = new RequestValidator();

\$argv = \$_SERVER['argv'];
array_shift(\$argv); // Remove script name

if (empty(\$argv) || in_array(\$argv[0], ['--help', '-h', 'help'])) {
    echo \$formatter->color("  ⚡ " . \$title . " CLI v" . \$version . "\\n", 'bold');
    echo \$formatter->color("  Base URL: " . \$baseUrl . "\\n\\n", 'dim');
    echo \$formatter->color("Usage:\\n", 'yellow');
    echo "  " . basename(__FILE__) . " <resource> <action> [options]\\n\\n";
    echo \$formatter->color("Available Resources & Commands:\\n", 'yellow');

    foreach (\$commands as \$res => \$actions) {
        echo "  " . \$formatter->color(str_pad(\$res, 16), 'green') . " " . implode(', ', array_keys(\$actions)) . "\\n";
    }

    echo "\\n" . \$formatter->color("Global Options:\\n", 'yellow');
    echo "  --table           Render output as an ANSI table (default for lists)\\n";
    echo "  --json            Output raw JSON\\n";
    echo "  --csv             Export response data as CSV\\n";
    echo "  --page=N          Pagination page number\\n";
    echo "  --limit=N         Records per page\\n";
    echo "  --auto-paginate   Automatically fetch all pages\\n";
    echo "  --profile=NAME    Use saved authentication profile\\n";
    echo "  --header=K:V      Provide custom HTTP header\\n";
    echo "  --help, -h        Display this help message\\n";
    exit(0);
}

\$resource = strtolower(\$argv[0]);
\$action = isset(\$argv[1]) && !str_starts_with(\$argv[1], '--') ? strtolower(\$argv[1]) : 'list';

if (!isset(\$commands[\$resource])) {
    echo \$formatter->color("Error: Unknown resource '{\$resource}'.\\n", 'red');
    exit(1);
}

if (!isset(\$commands[\$resource][\$action])) {
    \$avail = implode(', ', array_keys(\$commands[\$resource]));
    echo \$formatter->color("Error: Unknown action '{\$action}' for resource '{\$resource}'. Available: {\$avail}\\n", 'red');
    exit(1);
}

\$op = \$commands[\$resource][\$action];

// Parse flags and options
\$options = [];
\$customHeaders = [];
\$isTable = false;
\$isJson = false;
\$isCsv = false;
\$autoPaginate = false;
\$profileName = 'default';

foreach (\$argv as \$arg) {
    if (str_starts_with(\$arg, '--')) {
        \$clean = substr(\$arg, 2);
        if (\$clean === 'table') \$isTable = true;
        elseif (\$clean === 'json') \$isJson = true;
        elseif (\$clean === 'csv') \$isCsv = true;
        elseif (\$clean === 'auto-paginate') \$autoPaginate = true;
        elseif (str_starts_with(\$clean, 'header=')) {
            [\$hk, \$hv] = explode('=', substr(\$clean, 7), 2);
            \$customHeaders[\$hk] = \$hv;
        } elseif (str_starts_with(\$clean, 'profile=')) {
            \$profileName = substr(\$clean, 8);
        } elseif (str_contains(\$clean, '=')) {
            [\$k, \$v] = explode('=', \$clean, 2);
            \$options[\$k] = \$v;
        } else {
            \$options[\$clean] = true;
        }
    }
}

// Request validation
\$validation = \$validator->validateParameters(\$op['parameters'] ?? [], \$options);
if (!\$validation['valid']) {
    echo \$formatter->color("Validation Error(s):\\n", 'red');
    foreach (\$validation['errors'] as \$err) {
        echo "  - {\$err}\\n";
    }
    exit(1);
}

// Build URL path & query parameters
\$path = \$op['path'];
\$queryParams = [];
\$headers = \$customHeaders;

foreach (\$op['parameters'] ?? [] as \$param) {
    \$pName = \$param['name'];
    \$pIn = \$param['in'] ?? 'query';
    \$val = \$validation['coerced'][\$pName] ?? \$options[\$pName] ?? null;

    if (\$val !== null) {
        if (\$pIn === 'path') {
            \$path = str_replace('{' . \$pName . '}', (string)\$val, \$path);
        } elseif (\$pIn === 'query') {
            \$queryParams[\$pName] = \$val;
        } elseif (\$pIn === 'header') {
            \$headers[\$pName] = (string)\$val;
        }
    }
}

// Apply Saved Auth Profile if available
\$authProfile = \$authManager->getProfile(\$profileName);
if (\$authProfile) {
    \$authManager->applyAuth(\$authProfile, \$headers, \$queryParams);
}

\$client = new HttpClient(\$baseUrl);
\$method = \$op['method'];
\$body = null;
if (isset(\$options['body'])) {
    \$body = json_decode(\$options['body'], true) ?? \$options['body'];
}

try {
    if (\$autoPaginate && \$method === 'GET') {
        \$pagination = new PaginationHandler(\$client);
        \$limit = (int)(\$queryParams['limit'] ?? 50);
        \$records = \$pagination->paginateAll(\$method, \$path, \$queryParams, \$body, \$headers, 10, \$limit);
        \$res = ['status' => 200, 'json' => \$records, 'body' => json_encode(\$records)];
    } else {
        \$res = \$client->request(\$method, \$path, \$queryParams, \$body, \$headers);
    }

    if (\$isCsv) {
        \$items = (new PaginationHandler(\$client))->extractItemsFromResponse(\$res['json'] ?? []);
        echo \$formatter->renderCsv(\$items);
    } elseif (\$isJson || (!\$isTable && !is_array(\$res['json']))) {
        echo \$formatter->renderJson(\$res['json'] ?? \$res['body']);
    } else {
        \$items = (new PaginationHandler(\$client))->extractItemsFromResponse(\$res['json'] ?? []);
        echo \$formatter->renderTable(\$items);
    }
} catch (\\Exception \$e) {
    echo \$formatter->color("Execution Failed: " . \$e->getMessage() . "\\n", 'red');
    exit(1);
}
PHP;

        $targetFile = rtrim($outputDir, '/\\') . DIRECTORY_SEPARATOR . $name;
        if (DIRECTORY_SEPARATOR === '\\' && !str_ends_with($targetFile, '.bat') && !str_ends_with($targetFile, '.php')) {
            $cliScript = $targetFile . '.php';
            file_put_contents($cliScript, $template);
            @chmod($cliScript, 0755);

            // Also create a convenient .bat wrapper for Windows users
            $batContent = "@echo off\r\nphp \"%~dp0{$name}.php\" %*\r\n";
            file_put_contents($targetFile . '.bat', $batContent);
        } else {
            $cliScript = $targetFile;
            file_put_contents($cliScript, $template);
            @chmod($cliScript, 0755);
        }

        return $cliScript;
    }

    private function extractAction(string $method, string $path, string $operationId): string
    {
        $hasPathParam = str_contains($path, '{');

        if ($method === 'GET') {
            return $hasPathParam ? 'get' : 'list';
        }
        if ($method === 'POST') {
            return 'create';
        }
        if ($method === 'PUT') {
            return 'update';
        }
        if ($method === 'PATCH') {
            return 'patch';
        }
        if ($method === 'DELETE') {
            return 'delete';
        }

        return strtolower($method);
    }

    public function generateCommandTree(): array
    {
        $tree = [];
        foreach ($this->parser->getOperations() as $op) {
            $resource = $op['resource'];
            $action = $this->extractAction($op['method'], $op['path'], $op['operationId']);
            $tree[$resource][$action] = $op;
        }
        return $tree;
    }
}
